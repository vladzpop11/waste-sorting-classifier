"""Prepare web/ for publishing: the pinned ONNX Runtime Web files and the model record.

- web/vendor/: the ONNX Runtime Web files listed in web/vendor.json, downloaded and checked
  against their pinned SHA-256, so the page loads nothing from third parties.
- web/model-info.js: the evaluated model's SHA-256, classes and architecture, taken from
  models/model.json, and its low-confidence threshold from reports/val_errors.json
  (`make errors`). The page trusts these constants (part of its own code), not a JSON file
  sitting next to the model.
"""

import json

from waste_sorting_classifier.artifacts import sha256
from waste_sorting_classifier.config import project_path
from waste_sorting_classifier.fetch_model import fetch


def main() -> None:
    web = project_path("web")
    vendor = json.loads((web / "vendor.json").read_text())
    for name, expected in vendor["files"].items():
        dest = web / "vendor" / name
        if dest.exists() and sha256(dest) == expected:
            continue
        fetch(vendor["base_url"] + name, dest, expected)
    meta = json.loads(project_path("models/model.json").read_text())
    info = {"arch": meta["arch"], "classes": meta["classes"], "sha256": meta["onnx_sha256"]}
    errors = project_path("reports/val_errors.json")
    if errors.exists():
        analysis = json.loads(errors.read_text())
        if analysis["onnx_sha256"] != meta["onnx_sha256"]:
            raise SystemExit("reports/val_errors.json is for another model: run `make errors`")
        flag = analysis["low_confidence"]
        info["lowConfidence"] = {
            "threshold": flag["threshold"],
            "accuracyBelow": flag["accuracy_below"],
        }
    else:
        print("warning: no reports/val_errors.json, so no low-confidence note (run `make errors`)")
    (web / "model-info.js").write_text(
        "// Generated by `make web` from models/model.json: the evaluated model.\n"
        f"export const MODEL = {json.dumps(info, indent=2)};\n"
    )
    print(f"web/vendor: {len(vendor['files'])} files verified; web/model-info.js -> {info['arch']}")


if __name__ == "__main__":
    main()
