"""Prepare web/ for publishing: the pinned ONNX Runtime Web files and the model record.

- web/vendor/: ONNX Runtime Web and the WebAssembly image decoders listed in
  web/vendor.json, downloaded and checked against their pinned SHA-256, so the page loads
  nothing from third parties.
- web/model-info.js: the evaluated model's SHA-256, classes and architecture, taken from
  models/model.json, and its low-confidence threshold from reports/val_errors.json
  (`make errors`). The page trusts these constants (part of its own code), not a JSON file
  sitting next to the model.
- web/examples/: per class and source (TrashNet <class>.jpg, RealWaste <class>-real.jpg),
  the first validation photo (in path order) that the model gets right and the familiarity
  check accepts, copied byte for byte. Never a training or test photo.
"""

import json

from waste_sorting_classifier.artifacts import sha256
from waste_sorting_classifier.config import load_config, project_path
from waste_sorting_classifier.fetch_model import fetch
from waste_sorting_classifier.split import load_split


def copy_examples(classes: list[str], wrong: set[str]) -> None:
    cfg = load_config()
    images_dir = project_path(cfg["data"]["raw_dir"]) / "images"
    val = load_split(cfg, verify=False).query("split == 'val'").sort_values("path")
    folder = project_path("web/examples")
    for old in folder.glob("*.jpg"):
        old.unlink()
    # One studio photo (TrashNet) and one real-waste photo (RealWaste) per class.
    for source, suffix in [("trashnet", ""), ("realwaste", "-real")]:
        rows = val[val["source"] == source]
        for label in classes:
            path = next(p for p in rows.loc[rows["label"] == label, "path"] if p not in wrong)
            (folder / f"{label}{suffix}.jpg").write_bytes((images_dir / path).read_bytes())
            print(f"example {label}{suffix}: {path}")


def main() -> None:
    web = project_path("web")
    wasm = {}
    files = 0
    for package in json.loads((web / "vendor.json").read_text())["packages"]:
        for name, entry in package["files"].items():
            # "name": sha256, or "name": {"path": source path in the package, "sha256": ...}
            source = entry["path"] if isinstance(entry, dict) else name
            expected = entry["sha256"] if isinstance(entry, dict) else entry
            dest = web / "vendor" / name
            if not (dest.exists() and sha256(dest) == expected):
                fetch(package["base_url"] + source, dest, expected)
            if name.endswith(".wasm"):
                wasm[name] = expected
            files += 1
    meta = json.loads(project_path("models/model.json").read_text())
    info = {"arch": meta["arch"], "classes": meta["classes"], "sha256": meta["onnx_sha256"],
            "temperature": meta.get("calibration", {}).get("temperature", 1.0)}  # fmt: skip
    fam = meta["familiarity"]
    info["familiarity"] = {k: fam[k] for k in ["method", "file", "sha256", "classes", "dims",
                                               "threshold"]}  # fmt: skip
    errors = project_path("reports/val_errors.json")
    if errors.exists():
        analysis = json.loads(errors.read_text())
        if analysis["onnx_sha256"] != meta["onnx_sha256"]:
            raise SystemExit("reports/val_errors.json is for another model: run `make errors`")
        flag = analysis["low_confidence"]
        if flag["threshold"] is None:
            print("warning: no confidence threshold met the target, so no low-confidence note")
        else:
            info["lowConfidence"] = {
                "threshold": flag["threshold"],
                "accuracyBelow": flag["accuracy_below"],
                "accuracyAbove": flag["accuracy_above"],
            }
        unfamiliar = set(json.loads(project_path("reports/familiarity.json").read_text())
                         ["unfamiliar_validation_photos"])  # fmt: skip
        copy_examples(meta["classes"], {e["path"] for e in analysis["photos"]} | unfamiliar)
    else:
        print("warning: no reports/val_errors.json, so no low-confidence note (run `make errors`)")
    (web / "model-info.js").write_text(
        "// Generated by `make web`: the evaluated model (models/model.json) and the SHA-256 of\n"
        "// every WebAssembly file the page runs (web/vendor.json). The page checks them all.\n"
        f"export const MODEL = {json.dumps(info, indent=2)};\n"
        f"export const WASM = {json.dumps(wasm, indent=2)};\n"
    )
    print(f"web/vendor: {files} files verified; web/model-info.js -> {info['arch']}")


if __name__ == "__main__":
    main()
